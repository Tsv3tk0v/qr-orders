export type TKey = keyof typeof bg;
const DICTS: Record<Locale, Dict> = { bg, en };

interface I18n {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
  /** Динамичен ключ (напр. от код на грешка) с резервен текст. */
  tx: (key: string, fallback: TKey) => string;
  text: (t: I18nText) => string;
  price: (cents: number) => string;
  err: (e: unknown) => string;
}

const Ctx = createContext<I18n | null>(null);
const store = safeStorage('local');

export function I18nProvider({ children, initial, storageKey = 'locale' }:
  { children: ReactNode; initial?: Locale; storageKey?: string }) {
  const [locale, setLocaleState] = useState<Locale>(() => (store.get(storageKey) as Locale) || initial || 'bg');
  const value = useMemo<I18n>(() => {
    const d = DICTS[locale] ?? bg;
    const fill = (s: string, vars?: Record<string, string | number>) =>
      vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? '')) : s;
    const tx = (key: string, fallback: TKey) => (d as Record<string, string>)[key] ?? d[fallback];
    return {
      locale,
      setLocale: (l) => { store.set(storageKey, l); setLocaleState(l); document.documentElement.lang = l; },
      t: (key, vars) => fill(d[key] ?? key, vars),
      tx,
      text: (t) => pickText(t, locale),
      price: (c) => formatPrice(c, locale),
      err: (e) => tx(`err.${(e as { code?: string })?.code ?? 'generic'}`, 'err.generic'),
    };
  }, [locale, storageKey]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('I18nProvider липсва');
  return v;
}
